export const ASCII_SKILL_BAR = (filled: number, total: number = 12): string => {
  const filledChars = "█".repeat(filled);
  const emptyChars = "░".repeat(total - filled);
  return `[${filledChars}${emptyChars}]`;
};

export const ASCII_TREE = (items: string[]): string => {
  return items
    .map((item, index) => {
      const isLast = index === items.length - 1;
      const prefix = isLast ? "└─" : "├─";
      return `${prefix} ${item}`;
    })
    .join("\n");
};
